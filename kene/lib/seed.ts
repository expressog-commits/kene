function buildStock(now: number): StockItem[] {
  const stock: StockItem[] = [];
  for (const pharmacy of PHARMACIES) {
    for (const medicine of MEDICINES) {
      const key = `${pharmacy.id}:${medicine.id}`;
      const override = OVERRIDES[key];
      const seed = hash(key);
      if (!override && seed % 10 >= 9) continue;

      const quantity = override ? override.quantity : seed % 44;
      const price = override
        ? override.price
        : Math.round((medicine.basePrice * (90 + (seed % 21))) / 100 / 100) * 100;

      stock.push({
        pharmacyId: pharmacy.id,
        medicineId: medicine.id,
        price,
        quantity,
        updatedAt: new Date(now - (seed % 9) * 3600_000).toISOString(),
      });
    }
  }
  return stock;
}

